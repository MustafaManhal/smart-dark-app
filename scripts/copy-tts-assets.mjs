// What the worker imports as "transformers.js": the library, pointed at our own copy of the runtime.
writeFileSync(new URL("transformers-local.mjs", to), `// Generated by scripts/copy-tts-assets.mjs.
import { env } from "./vendor/transformers.min.js";
export * from "./vendor/transformers.min.js";

// Same choice transformers.js makes for its default (CDN) paths.
const oldSafari = !("gpu" in navigator) && /^((?!chrome|chromium|android|edg).)*safari/i.test(navigator.userAgent);
const name = oldSafari ? "ort-wasm-simd-threaded" : "ort-wasm-simd-threaded.asyncify";
const vendor = new URL("./vendor/", import.meta.url).href;
env.backends.onnx.wasm.wasmPaths = { mjs: vendor + name + ".mjs", wasm: vendor + name + ".wasm" };
// Loading the runtime through its cache imports a blob: script, which the app's security policy forbids.
env.useWasmCache = false;
env.allowLocalModels = false;
// Several threads make speech come faster than it is spoken. Browsers only allow
// them on cross-origin isolated pages (the COOP and COEP headers in vercel.json).
if (globalThis.crossOriginIsolated) {
  env.backends.onnx.wasm.numThreads = Math.max(1, Math.min(8, (navigator.hardwareConcurrency || 4) - 2));
}
// Tests read the model from their own server instead of Hugging Face (worker URL ?modelHost=...).
const modelHost = new URL(self.location.href).searchParams.get("modelHost");
if (modelHost) env.remoteHost = modelHost;
`);

// Voices: small files, fetched once and kept in node_modules/.cache.
mkdirSync(cache, { recursive: true });
let missing = 0;
for (const voice of VOICES) {
  const cached = new URL(`${voice}.bin`, cache);
  if (!existsSync(cached) || statSync(cached).size < 100_000) {
    try {
      const response = await fetch(`${VOICE_URL}${voice}.bin`);
      if (!response.ok) throw new Error(`HTTP ${response.status}`);
      writeFileSync(cached, Buffer.from(await response.arrayBuffer()));
    } catch (error) {
      missing++;
      console.warn(`voice ${voice} could not be fetched (${error.message}); the app will load it from Hugging Face`);
      continue;
    }
  }
  cpSync(cached, new URL(`voices/${voice}.bin`, to));
}
// The app reads this list to know which voices are local.
writeFileSync(new URL("voices/index.json", to), JSON.stringify(VOICES.filter((v) => existsSync(new URL(`voices/${v}.bin`, to)))));

const mb = (url) => (statSync(url).size / 1048576).toFixed(1);
console.log(`read-aloud assets copied to app/public/tts/ (${VOICES.length - missing} of ${VOICES.length} voices, runtime ${mb(new URL("vendor/ort-wasm-simd-threaded.asyncify.wasm", to))} MB)`);
