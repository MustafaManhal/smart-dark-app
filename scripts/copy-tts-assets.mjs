// Copies everything the natural (neural) read-aloud voices run on into
// app/public/tts/, so the app loads no script from another site:
//   headtts/       HeadTTS worker and its English pronunciation rules (MIT)
//   dictionaries/  pronunciation dictionary, from the CMU dictionary (BSD)
//   vendor/        transformers.js (Apache-2.0) and the ONNX Runtime wasm (MIT)
//   voices/        the 28 English Kokoro voices (Apache-2.0), fetched once
// The model itself (about 326 MB) is not shipped: the reader downloads it from
// Hugging Face when they turn natural voices on.
import { cpSync, existsSync, mkdirSync, rmSync, statSync, writeFileSync } from "node:fs";

const root = new URL("../", import.meta.url);
const modules = new URL("node_modules/", root);
const to = new URL("app/public/tts/", root);
const cache = new URL("node_modules/.cache/smart-dark-tts/voices/", root);

/** English voices of Kokoro v1.0: a = American, b = British; f = female, m = male. */
export const VOICES = [
  "af_heart", "af_bella", "af_nicole", "af_aoede", "af_kore", "af_sarah", "af_nova", "af_sky", "af_alloy", "af_jessica", "af_river",
  "am_michael", "am_fenrir", "am_puck", "am_echo", "am_eric", "am_liam", "am_onyx", "am_adam", "am_santa",
  "bf_emma", "bf_isabella", "bf_alice", "bf_lily",
  "bm_george", "bm_fable", "bm_lewis", "bm_daniel",
];
const VOICE_URL = "https://huggingface.co/onnx-community/Kokoro-82M-v1.0-ONNX/resolve/main/voices/";

rmSync(to, { recursive: true, force: true });
for (const dir of ["headtts", "dictionaries", "vendor", "voices"]) mkdirSync(new URL(`${dir}/`, to), { recursive: true });

const headtts = new URL("vendor/headtts/", root); // kept in the repository, see its README
for (const file of ["worker-tts.mjs", "utils.mjs", "language.mjs", "language-en-us.mjs"]) {
  cpSync(new URL(`modules/${file}`, headtts), new URL(`headtts/${file}`, to));
}
cpSync(new URL("LICENSE", headtts), new URL("headtts/LICENSE", to));
cpSync(new URL("dictionaries/en-us.txt", headtts), new URL("dictionaries/en-us.txt", to));

const transformers = new URL("@huggingface/transformers/", modules);
cpSync(new URL("dist/transformers.min.js", transformers), new URL("vendor/transformers.min.js", to));
cpSync(new URL("LICENSE", transformers), new URL("vendor/LICENSE-transformers", to));

// transformers.js pins the ONNX Runtime build it was made for; take that one.
const ortPaths = ["@huggingface/transformers/node_modules/onnxruntime-web/", "onnxruntime-web/"];
const ort = ortPaths.map((p) => new URL(p, modules)).find((u) => existsSync(u));
if (!ort) throw new Error("onnxruntime-web is not installed");
for (const name of ["ort-wasm-simd-threaded.asyncify", "ort-wasm-simd-threaded"]) {
  for (const ext of ["mjs", "wasm"]) cpSync(new URL(`dist/${name}.${ext}`, ort), new URL(`vendor/${name}.${ext}`, to));
}
